"""Founder portrait sequence.

Nine photographs of the same session, in playing order: no glasses -> hand to pocket -> glasses out ->
held -> lifted -> on the face -> arms crossed with glasses -> the high resolution final.

Every frame is registered to the first one (head and collar features, similarity transform), so the head
stays still while only the hands and the glasses move. The final frame is a tighter, darker exposure; its
shadows are lifted a little to match the rest. No retouching otherwise.

Reads  <assets>/founder/<n>.webp   (the photographs as supplied)
Writes public/founder/f<i>-<w>.webp, public/founder/lqip.txt and src/lib/founder.js

Usage: python scripts/build-founder.py [assets_dir]
"""
import base64, io, json, os, sys
import cv2
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = sys.argv[1] if len(sys.argv) > 1 else r"E:/Startup/Hydris/website/0. assets/founder"
OUT = os.path.join(ROOT, "public", "founder")
os.makedirs(OUT, exist_ok=True)

ORDER = [23, 25, 26, 27, 28, 29, 30, 31, 24]
REF = 23
W, H = 1600, 2000
WIDTHS = [800, 1200]
BIG = {0, len(ORDER) - 1}          # the two resting frames also get a 1600 version
BG = (31, 31, 31)

def load(n):
    return cv2.imread(os.path.join(ASSETS, f"{n}.webp"), cv2.IMREAD_COLOR)

clahe = cv2.createCLAHE(clipLimit=3.0, tileGridSize=(8, 8))
gray = lambda im: clahe.apply(cv2.cvtColor(im, cv2.COLOR_BGR2GRAY))

ref = load(REF)
assert ref.shape[:2] == (H, W), ref.shape
mask = np.zeros((H, W), np.uint8)
mask[int(0.05 * H):int(0.42 * H), int(0.28 * W):int(0.78 * W)] = 255
sift = cv2.SIFT_create(nfeatures=4000, contrastThreshold=0.01)
kr, dr = sift.detectAndCompute(gray(ref), mask)

def lift_shadows(img, lift=(14, 12, 11), knee=80.0, gain=(1.0, 0.97, 0.94)):
    """Raise only the darkest tones (the studio background) and warm nothing else."""
    f = img.astype(np.float32)
    out = f.copy()
    for c in range(3):                      # BGR
        k = lift[2 - c]
        w = np.clip(1.0 - f[..., c] / knee, 0, 1) ** 2
        out[..., c] = f[..., c] * gain[2 - c] + k * w
    return np.clip(out, 0, 255).astype(np.uint8)

frames = []
for n in ORDER:
    img = load(n)
    h, w = img.shape[:2]
    if n == REF:
        frames.append(ref); continue
    s0 = W / w
    big = cv2.resize(img, (W, int(round(h * s0))), interpolation=cv2.INTER_CUBIC)
    gh, gw = big.shape[:2]
    gm = np.zeros((gh, gw), np.uint8)
    gm[int(0.04 * gh):int(0.46 * gh), int(0.2 * gw):int(0.82 * gw)] = 255
    k, d = sift.detectAndCompute(gray(big), gm)
    raw = cv2.BFMatcher(cv2.NORM_L2).knnMatch(d, dr, k=2)
    good = [m for m, n2 in raw if m.distance < 0.75 * n2.distance]
    src = np.float32([k[m.queryIdx].pt for m in good]); dst = np.float32([kr[m.trainIdx].pt for m in good])
    M, inl = cv2.estimateAffinePartial2D(src, dst, method=cv2.RANSAC, ransacReprojThreshold=2.5, maxIters=5000, confidence=0.999)
    assert M is not None and inl.sum() >= 40, f"frame {n}: too few inliers"
    if n == 24:
        big = lift_shadows(big)
    frames.append(cv2.warpAffine(big, M, (W, H), flags=cv2.INTER_CUBIC, borderMode=cv2.BORDER_REPLICATE))
    print(f"frame {n}: {int(inl.sum())} inliers, scale {np.hypot(M[0,0], M[1,0]):.3f}, shift {M[0,2]:.0f},{M[1,2]:.0f}")

manifest = []
for i, fr in enumerate(frames):
    rgb = Image.fromarray(cv2.cvtColor(fr, cv2.COLOR_BGR2RGB))
    widths = WIDTHS + ([1600] if i in BIG else [])
    for wd in widths:
        im = rgb if wd == W else rgb.resize((wd, wd * H // W), Image.LANCZOS)
        im.save(os.path.join(OUT, f"f{i}-{wd}.webp"), "WEBP", quality=82, method=6)
    manifest.append({"i": i, "src": ORDER[i], "widths": widths})

lq = Image.fromarray(cv2.cvtColor(frames[0], cv2.COLOR_BGR2RGB)).resize((24, 30), Image.LANCZOS)
buf = io.BytesIO(); lq.save(buf, "WEBP", quality=60)
lqip = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()

js = f"""/* Generated by scripts/build-founder.py. Nine frames of one session, registered so the head holds still. */
export const FOUNDER = {{
  ratio: [{W}, {H}],
  bg: 'rgb({BG[0]}, {BG[1]}, {BG[2]})',
  lqip: '{lqip}',
  frames: {json.dumps(manifest)},
}};
"""
open(os.path.join(ROOT, "src", "lib", "founder.js"), "w", encoding="utf-8").write(js)
total = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
print(len(frames), "frames,", round(total / 1024), "KB total")
